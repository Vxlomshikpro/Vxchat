package ru.vxlomshikpro.vxchat.cipher;

/**
 * Шифр чата VXChat.
 *
 * <p>Намеренно узкий контракт: {@link #encrypt(String)} и {@link #decrypt(String)}.
 * Реализация {@link GlyphCipher} — статическая подстановка «один символ → один
 * иероглиф». Интерфейс существует, чтобы позже можно было подключить другие
 * режимы (перемешивание по ключу, другой алфавит, шифр с состоянием), не трогая
 * ни клиент, ни хендшейк, ни GUI: им всё равно, что внутри — только два метода.
 *
 * <p>Реализации обязаны быть:
 * <ul>
 *   <li><b>детерминированными</b> — тот же текст даёт тот же шифротекст, иначе
 *       собеседник ничего не расшифрует;</li>
 *   <li><b>обратимыми</b> — {@code decrypt(encrypt(s)) == s} для любого текста,
 *       который шифр вообще принимает к шифрованию.</li>
 * </ul>
 */
public interface Cipher {

    /**
     * Зашифровать текст для отправки в чат.
     *
     * @param plain открытый текст, как его набрал игрок
     * @return текст с иероглифами вместо букв; символы вне таблицы остаются как есть
     */
    String encrypt(String plain);

    /**
     * Расшифровать текст, пришедший в чат.
     *
     * @param cipherText текст с иероглифами
     * @return открытый текст; неизвестные символы остаются как есть
     */
    String decrypt(String cipherText);

    /**
     * Похоже ли, что строка зашифрована этим шифром.
     *
     * <p>Нужен, чтобы не переписать обычное китайское сообщение в мусор и чтобы
     * решить, стоит ли вообще пытаться расшифровывать (пункт 3 ТЗ: если
     * иероглифов из таблицы в сообщении нет — показывать оригинал).
     *
     * @param text проверяемая строка
     * @return true, если в строке есть символы из таблицы шифра
     */
    boolean looksEncrypted(String text);

    /**
     * Есть ли в шифре глиф для символа.
     *
     * @param c символ
     * @return true, если символ шифруется этим шифром
     */
    boolean encrypts(char c);

    /**
     * Максимальная длина сообщения, которую шифр готов принять.
     *
     * @return лимит в символах исходного текста
     */
    int maxPlainLength();
}